// Give generated computing products realistic model names
(function nameComputing() {
  const names = [
    'Atlas Mini 13',
    'Core Station S',
    'PulseBook Pro 16',
    'EdgeBook 14',
    'Atlas WorkPad 11',
    'StudioDeck 24',
    'NanoPC Mini',
    'WorkMate Desktop'
  ];
  let i = 0;
  for (const p of demoProducts) {
    if (p.category === 'Computing' && p._id !== 'demo-2' && p._id !== 'demo-8') {
      if (i < names.length) p.title = names[i++];
      else p.title = `Computing ${p._id}`;
    }
  }
})();
